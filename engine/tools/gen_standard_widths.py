"""Regenerates pdfcore/src/standard_widths.rs (see the header it writes).

Dev-only: reads Adobe's standard-font metrics through PyMuPDF once, so the
engine ships plain data and no PyMuPDF.

    python3 tools/gen_standard_widths.py
"""
import pathlib
import pymupdf

FONTS = [("HELVETICA", "helv"), ("HELVETICA_BOLD", "hebo"), ("TIMES", "tiro"),
         ("TIMES_BOLD", "tibo"), ("TIMES_ITALIC", "tiit"), ("TIMES_BOLD_ITALIC", "tibi"),
         ("COURIER", "cour")]

out = ["//! Advance widths of the standard fonts a PDF may name without embedding or\n",
       "//! giving a `/Widths` array, in thousandths of the font size, for codes 32..=255\n",
       "//! of WinAnsiEncoding. Generated by `tools/gen_standard_widths.py` from Adobe's\n",
       "//! published metrics; do not edit by hand.\n\n"]
for const, name in FONTS:
    font = pymupdf.Font(name)
    widths = []
    for code in range(32, 256):
        ch = bytes([code]).decode("cp1252", errors="replace")
        widths.append(round(font.text_length(ch, fontsize=1000)) if ch != "�" else 0)
    out.append(f"pub const {const}: [u16; 224] = [\n")
    for i in range(0, 224, 16):
        out.append("    " + ", ".join(str(w) for w in widths[i:i + 16]) + ",\n")
    out.append("];\n\n")

target = pathlib.Path(__file__).resolve().parents[1] / "pdfcore/src/standard_widths.rs"
target.write_text("".join(out).rstrip() + "\n")
print("wrote", target)
