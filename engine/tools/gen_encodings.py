"""Writes pdfcore/src/encodings_data.rs: the simple-font encodings and the glyph names.

 - StandardEncoding: Adobe's table (typed in below, from the PDF specification, Annex D).
 - WinAnsi, MacRoman: Python's cp1252 / mac_roman codecs with the PDF specification's changes.
 - Symbol: measured with MuPDF (PyMuPDF is only an oracle, never shipped): every code is
   drawn in the standard Symbol font and the text MuPDF extracts is recorded.
 - Adobe Glyph List (glyphlist.txt, BSD-3-Clause, license in pdfcore/fonts): name -> Unicode.

    python3 tools/gen_encodings.py
"""
import pathlib, pymupdf

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "pdfcore/src/encodings_data.rs"

STANDARD_HIGH = {
    0x27: "’", 0x60: "‘",
    0xA1: "¡", 0xA2: "¢", 0xA3: "£", 0xA4: "⁄", 0xA5: "¥", 0xA6: "ƒ", 0xA7: "§", 0xA8: "¤", 0xA9: "'",
    0xAA: "“", 0xAB: "«", 0xAC: "‹", 0xAD: "›", 0xAE: "ﬁ", 0xAF: "ﬂ",
    0xB1: "–", 0xB2: "†", 0xB3: "‡", 0xB4: "·", 0xB6: "¶", 0xB7: "•", 0xB8: "‚",
    0xB9: "„", 0xBA: "”", 0xBB: "»", 0xBC: "…", 0xBD: "‰", 0xBF: "¿",
    0xC1: "`", 0xC2: "´", 0xC3: "ˆ", 0xC4: "˜", 0xC5: "¯", 0xC6: "˘", 0xC7: "˙", 0xC8: "¨", 0xCA: "˚",
    0xCB: "¸", 0xCD: "˝", 0xCE: "˛", 0xCF: "ˇ", 0xD0: "—",
    0xE1: "Æ", 0xE3: "ª", 0xE8: "Ł", 0xE9: "Ø", 0xEA: "Œ", 0xEB: "º",
    0xF1: "æ", 0xF5: "ı", 0xF8: "ł", 0xF9: "ø", 0xFA: "œ", 0xFB: "ß",
}


def standard():
    return [STANDARD_HIGH.get(c, chr(c) if 32 <= c <= 126 else "") for c in range(256)]


def win_ansi():
    table = []
    for c in range(256):
        if c < 32 or c == 0x7F:
            table.append("")
        elif 0x80 <= c <= 0x9F:
            try:
                table.append(bytes([c]).decode("cp1252"))
            except UnicodeDecodeError:
                table.append("")
        elif c == 0xA0:
            table.append(" ")
        elif c == 0xAD:
            table.append("-")
        else:
            table.append(chr(c))
    table[0x7F] = "•"  # the specification lets 127 and the undefined slots show a bullet
    return table


def mac_roman():
    table = []
    for c in range(256):
        if c < 32 or c == 0x7F:
            table.append("")
        elif c == 0xCA:
            table.append(" ")
        elif c == 0xDB:
            table.append("¤")  # the PDF table has the currency sign where Apple's has the euro
        else:
            table.append(bytes([c]).decode("mac_roman"))
    return table


def symbol():
    """Every code of the Symbol font, as MuPDF reads it (one code per page, so nothing merges)."""
    codes = [c for c in range(32, 256) if c != 127]
    objects = {1: b"<</Type/Catalog/Pages 2 0 R>>", 5: b"<</Type/Font/Subtype/Type1/BaseFont/Symbol>>"}
    kids = []
    for i, c in enumerate(codes):
        page, content = 10 + 2 * i, 11 + 2 * i
        kids.append(b"%d 0 R" % page)
        body = b"BT /F1 20 Tf 20 20 Td <%02X> Tj ET" % c
        objects[page] = b"<</Type/Page/Parent 2 0 R/MediaBox[0 0 60 60]/Contents %d 0 R/Resources<</Font<</F1 5 0 R>>>>>>" % content
        objects[content] = b"<</Length %d>>\nstream\n" % len(body) + body + b"\nendstream"
    objects[2] = b"<</Type/Pages/Count %d/Kids[%s]>>" % (len(codes), b" ".join(kids))
    out, offsets = b"%PDF-1.7\n", {}
    for n in sorted(objects):
        offsets[n] = len(out)
        out += b"%d 0 obj\n" % n + objects[n] + b"\nendobj\n"
    start, size = len(out), max(objects) + 1
    out += b"xref\n0 %d\n" % size + b"0000000000 65535 f \n"
    out += b"".join(b"%010d 00000 n \n" % offsets[n] if n in offsets else b"0000000000 65535 f \n" for n in range(1, size))
    out += b"trailer\n<</Size %d/Root 1 0 R>>\nstartxref\n%d\n%%%%EOF\n" % (size, start)
    doc = pymupdf.open(stream=out, filetype="pdf")
    table = [""] * 256
    for c, page in zip(codes, doc):
        table[c] = page.get_text().strip()
    table[32] = " "
    return table


def agl():
    entries = []
    for line in (ROOT / "tools/glyphlist.txt").read_text().splitlines():
        if line.startswith("#") or ";" not in line:
            continue
        name, codes = line.split(";")
        entries.append((name, "".join(chr(int(c, 16)) for c in codes.split())))
    return sorted(entries)


def rust_str(text):
    return '"' + "".join(f"\\u{{{ord(ch):X}}}" for ch in text) + '"'


def array(name, table):
    rows = ",\n    ".join(", ".join(rust_str(t) for t in table[i:i + 8]) for i in range(0, 256, 8))
    return f"pub static {name}: [&str; 256] = [\n    {rows},\n];\n"


if __name__ == "__main__":
    out = "// Generated by tools/gen_encodings.py. Do not edit.\n\n"
    for name, table in (("STANDARD", standard()), ("WIN_ANSI", win_ansi()), ("MAC_ROMAN", mac_roman()), ("SYMBOL", symbol())):
        out += array(name, table) + "\n"
    out += "/// Adobe Glyph List (BSD-3-Clause, see fonts/LICENSE-AdobeGlyphList-BSD3.txt), sorted by name.\n"
    out += "pub static AGL: &[(&str, &str)] = &[\n"
    out += "".join(f"    ({rust_str(n)[:0] or chr(34) + n + chr(34)}, {rust_str(t)}),\n" for n, t in agl())
    out += "];\n"
    OUT.write_text(out)
    print("wrote", OUT, len(agl()), "glyph names")
